"""CP6: write the fitted-model section of data/DATASET.md from fitted_params.json + validation_report.md.

python -m generator.fit.report          # rewrite the block between the markers
python -m generator.fit.report --check  # exit 1 if the block in DATASET.md differs from what the data says
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "data" / "DATASET.md"
PARAMS = ROOT / "generator" / "fitted_params.json"
REPORT = ROOT / "data" / "validation_report.md"
MANIFEST = ROOT / "data" / "external" / "MANIFEST.json"
START, END = "<!-- FITTED-MODEL:START (generated by generator/fit/report.py) -->", "<!-- FITTED-MODEL:END -->"

USED_FOR = [
    ("ar1_phi_cpu", "CPU AR(1) phi (all bulk VMs; planted except pinned)"),
    ("ar1_phi_cpu_azure", "cross-check only"),
    ("drift_sd", "fleet day-to-day drift (fallback when an archetype has < 30 real matches)"),
    ("weekend_factor_interactive", "weekend factor, interactive VMs"),
    ("mem_ar1_phi", "memory AR(1) phi"),
    ("mem_coupling", "memory-on-CPU slope"),
    ("mem_noise_sd_pct", "memory noise sd (pct points)"),
    ("net_base_over_k", "network intercept / slope ratio"),
    ("net_lognorm_sigma", "network lognormal spread"),
    ("net_out_in_ratio", "net_out / net_in"),
    ("iops_base_alibaba", "disk IO intercept (% of provisioned)"),
    ("iops_k_alibaba", "disk IO slope on CPU"),
    ("iops_lognorm_sigma", "disk IO lognormal spread"),
    ("missing_share_bitbrains", "random monitoring-gap rate"),
]

ASSUMED = [
    "Network absolute scale: a VM at 30% CPU uses a median 1% of its plan bandwidth (Bitbrains has no link capacity).",
    "Disk-used % level and slope (no public trace records disk-used %).",
    "Peak hour 14:00 IST (scenario: Indian business hours). Bitbrains interactive VMs peak at "
    "{peak:.0f}:00 local time (Netherlands) - reported, deliberately not copied.",
    "Archetype MIX and counts (scenario), prices, regions, teams, plans, planted edge cases.",
    "Levels for batch_nightly, office_hours_dev and bursty_daily: fewer than 30 real VMs matched their definition "
    "(n = {nb}, {no}, {nbu}), so their levels stay hand-set; their noise and drift are fitted.",
    "memory_bound memory level 80-85%: no public VM trace here has memory % (Alibaba mem% is per container limit).",
    "right_sized_prod drift capped at 0.10 and noise capped so p99 < 88 (real right-sized VMs often saturate: "
    "p99 median {rsp99}%), otherwise the 'healthy' label would be false.",
]


def build_block():
    P = json.loads(PARAMS.read_text())
    a = P["archetypes"]
    from generator.planted import PINNED
    lines = [START, "", "## How the signals are built (fitted to real traces)", "",
             "Each VM is vectorised over 8,640 slots. Values below are read from `generator/fitted_params.json`, "
             "produced by `python -m generator.fit.fit` from the public traces listed under *Sources*.", "",
             "```",
             f"cpu  = clip((trough + (peak - trough) x daily(t)) x drift(day) + AR1(sigma, phi={P['ar1_phi_cpu']['value']:.3f})) x weekly(t)",
             f"       sigma, trough, peak, drift, weekly: resampled from ONE real VM of the same archetype",
             f"       (fallback sigma = {P['ar1_sigma_model']['a']:.3f} x level^{P['ar1_sigma_model']['b']:.3f})",
             f"mem  = clip(mem_base + {P['mem_coupling']['value']:.4f} x cpu + AR1(sd={P['mem_noise_sd_pct']['value']:.2f}, phi={P['mem_ar1_phi']['value']:.3f}))",
             f"iops = provisioned x ({max(P['iops_base_alibaba']['value'], 0):.2f} + {max(P['iops_k_alibaba']['value'], 0):.4f} x cpu)% x lognormal(0, {P['iops_lognorm_sigma']['value']:.3f})",
             f"net_in  = bandwidth x k x ({max(P['net_base_over_k']['value'], 0):.1f} + cpu)% x lognormal(0, {P['net_lognorm_sigma']['value']:.3f})",
             f"net_out = {P['net_out_in_ratio']['value']:.3f} x net_in x lognormal(0, 0.2)",
             f"drift  = lognormal multiplier per day, sd = archetype median (steady_low {a['steady_low']['drift_sd']['p50']}, "
             f"zombie {a['zombie']['drift_sd']['p50']}, fleet {P['drift_sd']['value']:.3f})",
             f"spikes (right-sized) = Poisson {a['right_sized_prod']['spikes_per_day']['p50']}/day, "
             f"{a['right_sized_prod']['spike_excess_mad']['p25']}-{a['right_sized_prod']['spike_excess_mad']['p75']} MAD above the median",
             f"gaps   = {P['missing_share_bitbrains']['value'] * 100:.2f}% random missing samples",
             "```", "",
             "| Parameter | Used for | Real median | Real IQR | n | Source |", "|---|---|---|---|---|---|"]
    for k, use in USED_FOR:
        e = P[k]
        lines.append(f"| `{k}` | {use} | {e['value']:.4g} | {e['p25']:.4g} - {e['p75']:.4g} | {e['n_series']} | {e['source']} |")
    lines += ["", "Archetype parameter tuples (trough, peak, sigma, drift, weekend factor) are **resampled from real VMs** "
              "classified with the same rules, keeping only tuples that satisfy the archetype's definition:", "",
              "| Archetype | Real VMs matched | Used |", "|---|---|---|"]
    for name, v in a.items():
        lines.append(f"| {name} | {v.get('n_series', 0)} | {'resampled' if v.get('usable') else 'hand-set level (n < 30)'} |")

    rows = [l for l in REPORT.read_text(encoding="utf-8").splitlines()
            if l.startswith("| FIT ") or l.startswith("| CAL ") or l.startswith("| INFO ")]
    lines += ["", "## Real vs synthetic (from validation_report.md)", "",
              "| case | statistic | check | result | synthetic |", "|---|---|---|---|---|"] + rows
    rest = [l for l in REPORT.read_text(encoding="utf-8").splitlines() if " checks passed." in l]
    lines += ["", rest[0] if rest else ""]

    lines += ["", "## Not fitted (stated assumptions)", ""]
    lines += ["- " + t.format(peak=P["peak_hour_local"]["value"], nb=a["batch_nightly"]["n_series"],
                              no=a["office_hours_dev"]["n_series"], nbu=a["bursty_daily"]["n_series"],
                              rsp99=a["right_sized_prod"]["p99"]["p50"]) for t in ASSUMED]
    lines += ["", "## Pinned planted cases (keep hand-set dynamics phi 0.8, drift 0.05)", "",
              "Every other planted VM uses the fitted dynamics. A pin exists only where fitted noise/drift breaks the "
              "edge case's exact target:", "", "| Resource | Why pinned |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in PINNED.items()]

    lines += ["", "## Sources", "", "| Trace | Mirror file | sha256 | Licence / terms |", "|---|---|---|---|"]
    prov = P["_provenance"]
    lic = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    for k, v in prov.items():
        lines.append(f"| {k} | {v['url']} | `{v['sha256'][:16]}` | {lic.get(k, {}).get('license', 'see mirror')} |")
    lines += ["", "Findings worth knowing: Bitbrains memory (KB) is **not** steadier than CPU (CV "
              f"{P['calibration']['median_mem_cv']['bitbrains']} vs {P['calibration']['median_cpu_cv']['bitbrains']}); "
              "Alibaba and Borg are, so the 'memory steadier' check cites those two. Real network traffic is much "
              f"burstier than first assumed (lognormal sigma {P['net_lognorm_sigma']['value']:.2f} vs 0.35 hand-set).",
              "", END]
    return "\n".join(lines)


def main():
    doc = DOC.read_text(encoding="utf-8")
    block = build_block()
    if START not in doc:
        raise SystemExit("markers missing in DATASET.md")
    current = doc[doc.index(START):doc.index(END) + len(END)]
    if "--check" in sys.argv:
        ok = current == block
        print("DATASET.md fitted block", "matches data" if ok else "DIFFERS from data")
        raise SystemExit(0 if ok else 1)
    DOC.write_text(doc.replace(current, block), encoding="utf-8")
    print("DATASET.md fitted block written")


if __name__ == "__main__":
    main()
