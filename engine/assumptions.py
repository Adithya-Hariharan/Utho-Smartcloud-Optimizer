"""Generate ASSUMPTIONS.md (repo root): the engine's 'thresholds half' + presets, scorecard, alerts, benchmark and
the 'why this logic' summary. The data half lives in data/DATASET.md (data branch). Every number comes from
engine/config.yaml or a measured output file, so this document cannot drift from the code.

python -m engine.assumptions           write ASSUMPTIONS.md
python -m engine.assumptions --check   exit 1 if ASSUMPTIONS.md differs from what the inputs say"""
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "ASSUMPTIONS.md"
CFG = yaml.safe_load((HERE / "config.yaml").read_text(encoding="utf-8"))
CAT = {"M": "measured", "C": "cited default", "D": "derived", "S": "scenario", "J": "judgement"}
SECTIONS = [("percentiles", "Sizing percentiles"), ("gates_data", "Data sufficiency"), ("gates_policy", "Policy"),
            ("clean", "Data cleaning"), ("peaks", "Peaks"), ("vetoes", "Vetoes"), ("patterns", "Patterns"),
            ("candidates", "Candidate actions"), ("sizing", "Sizing and Peak Replay"), ("noncompute", "Volumes, IPs, stopped VMs"),
            ("risk", "Risk"), ("cost", "Cost"), ("alerts", "Alerts"), ("backtest", "Backtest")]


def _load(p):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def build():
    sel = _load(HERE / "selection.json") or {}
    log = _load(HERE / "selection_log.json") or []
    presets = _load(HERE / "presets_report.json") or {}
    bench = _load(HERE / "benchmark.json") or {}
    score = _load(ROOT / "data" / "scorecard.json") or {}
    alerts = _load(ROOT / "data" / "alerts.json") or {"items": [], "counts": {}}
    L = ["# Assumptions", "",
         "Two halves, as planned: the **data half** (prices, simulated fleet, fitted traces, data-quality faults) is "
         "`data/DATASET.md`; the **engine half** (every threshold, preset and rule the decisions use) is below. "
         "Generated by `python -m engine.assumptions` from `engine/config.yaml` and the measured outputs; full "
         "reasoning for each logic choice and each number is in `engine/REASONING.md`.", "",
         "## Pricing and billing (summary of the data half)", "",
         "- Prices are **illustrative**, modelled on Utho's public Basic tiers, INR, excluding GST; 730 h per month; all "
         "regions priced the same; no reserved-instance discounts or egress charges.",
         "- Block storage Rs 8/GB-month, snapshots Rs 4/GB-month, public IP Rs 200/month.",
         "- A stopped VM pays for its disk only (`stopped_vm_billed = false`): scheduling saves compute, never storage.",
         "- Savings are **sequential**, never additive: each action is priced on what the previous one left.", "",
         "## Engine thresholds", "",
         "Category: M measured on our data or the fitted traces, C cited published default, D derived, S scenario, J judgement.", ""]
    for sec, title in SECTIONS:
        body = CFG.get(sec, {})
        rows = [(k, v) for k, v in body.items() if isinstance(v, dict) and "value" in v]
        if not rows:
            continue
        L += [f"### {title}", "", "| threshold | value | category | why |", "|---|---|---|---|"]
        L += [f"| `{sec}.{k}` | {v['value']} | {v['category']} ({CAT[v['category']]}) | {v['why']} |" for k, v in rows]
        L.append("")
    L += ["## Presets", "",
          "Presets change only the sizing percentile, the CPU target and the replay overload budget. Measured on this "
          "fleet (same selected logic):", "",
          "| preset | percentile prod/non-prod | CPU target prod/non-prod | replay budget min/month | saving | unsafe in held-out week | risk levels |",
          "|---|---|---|---|---|---|---|"]
    for p, v in presets.items():
        L.append(f"| {p} | {v['percentile_prod']} / {v['percentile_nonprod']} | {v['target_cpu_prod']} / {v['target_cpu_nonprod']} | "
                 f"{v['budget_prod']} / {v['budget_nonprod']} | Rs {v['saving_inr']:,} ({v['saving_pct']}%) | "
                 f"{v['backtest_unsafe']}/{v['backtest_evaluated']} | {v['risk_levels']} |")
    if presets:
        sav = [v["saving_pct"] for v in presets.values()]
        L += ["", f"**Reading.** Savings move only from {min(sav)}% to {max(sav)}% across presets. A lower percentile does "
              "make more VMs *look* underused, but Peak Replay's overload line, the memory caps, the recurring-peak "
              "veto and the one-step prod rule are preset-independent and refuse the extra cuts. The binding "
              "constraint is replayed overload, not the sizing percentile: the safety gates are doing real work, and no "
              "preset buys savings with unsafe changes on this fleet."]
    L += ["", "## Why this logic (summary)", "", "| CP | component | selected | score /10 | runner-up |", "|---|---|---|---|---|"]
    for e in log:
        sc = e["initial"]
        for p in e["passes"]:
            sc = p.get("rescored_current") or sc
        ranked = sorted(sc, key=lambda s: (-s["total"], s["params"]))
        ru = next((s for s in ranked if s["candidate"] != sel.get(e["component"])), None)
        L.append(f"| {e['checkpoint']} | {e['component']} | `{sel.get(e['component'])}` | {e['selected_total']} | "
                 + (f"`{ru['candidate']}` {ru['total']}" if ru else "-") + " |")
    if score:
        L += ["", "## Engine scorecard", "",
              f"Engine vs truth.csv: **{score['correct']}/{score['rows']}** rows (verdict + reason code)"
              + (" - label disputes active on this dataset, see `engine/disputes.py`." if score["disputes_active"] else "."), "",
              "| headline | result |", "|---|---|"]
        L += [f"| {k} | {v} |" for k, v in score["headline"].items()]
        L += ["", "| group | rows | correct | recall |", "|---|---|---|---|"]
        L += [f"| {g} | {v['rows']} | {v['correct']} | {v['recall']} |" for g, v in score["per_group"].items()]
        L += ["", "| verdict | expected | predicted | precision | recall |", "|---|---|---|---|---|"]
        L += [f"| {c} | {v['expected']} | {v['predicted']} | {v['precision']} | {v['recall']} |" for c, v in score["per_verdict"].items()]
    L += ["", "## Alerts", "", f"{len(alerts['items'])} alerts on this fleet: {alerts.get('counts', {})}. Each states the "
          "number, the threshold and why it fired (`data/alerts.json`).", "", "| type | count |", "|---|---|"]
    types = {}
    for a in alerts["items"]:
        types[a["type"]] = types.get(a["type"], 0) + 1
    L += [f"| {t} | {n} |" for t, n in sorted(types.items())]
    if bench:
        s = bench["seconds"]
        L += ["", "## Scale benchmark", "",
              f"{bench['vms']:,} VMs ({bench['copies']}x the demo fleet, {bench['metric_rows']:,} metric rows) processed in "
              f"**{s['total']} s** on one process ({bench['ms_per_vm']} ms per VM; clean {s['clean']} s, evidence + decisions "
              f"{s['evidence_and_decisions']} s, alerts {s['alerts']} s; peak memory ~{bench['rss_mb']} MB) on "
              f"{bench['machine']['system']} / Python {bench['machine']['python']}. {bench['note']}. Beyond ~10k VMs: "
              "pre-aggregate hourly percentiles in a columnar store (DuckDB / ClickHouse) and run the engine per region in parallel."]
    L += ["", "## Engine simplifications (stated, not hidden)", "",
          "- CPU % is assumed to scale linearly with vCPU count in Peak Replay; headroom and the one-step prod rule absorb the error.",
          "- Memory used (GB) is assumed unchanged by a resize; only the percentage changes.",
          "- 30-day window: yearly seasonality is invisible, which is why the `seasonal_peak` tag exists.",
          "- Aggregate CPU hides a single saturated thread.",
          "- No reserved instances, savings plans or egress charges; prices are illustrative.",
          "- Recommendations are never auto-applied: every one carries before/after evidence and a rollback."]
    return "\n".join(L) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("ASSUMPTIONS.md", "matches inputs" if ok else "DIFFERS from inputs")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.name)


if __name__ == "__main__":
    main()
